def predict_sentiment_final(review):
    text = review.lower().strip()

    # Handle very obvious negative expressions
    negative_phrases = [
        "very bad",
        "really bad",
        "so bad",
        "extremely bad",
        "terrible",
        "terrible product",
        "awful",
        "horrible",
        "worst",
        "very disappointing",
        "completely disappointing",
        "hate it",
        "waste of money"
    ]

    # Handle very obvious positive expressions
    positive_phrases = [
        "very good",
        "really good",
        "so good",
        "excellent",
        "excellent product",
        "amazing",
        "awesome",
        "perfect",
        "love it",
        "really love",
        "highly recommend"
    ]

    for phrase in negative_phrases:
        if phrase in text:
            return "Negative"

    for phrase in positive_phrases:
        if phrase in text:
            return "Positive"

    # Otherwise use the trained ML model
    cleaned = clean_text(review)
    processed = remove_stopwords(cleaned)
    review_tfidf = tfidf_final.transform([processed])

    return lr_final.predict(review_tfidf)[0]

